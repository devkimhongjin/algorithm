SELECT
    YEAR(D1.DIFFERENTIATION_DATE) YEAR,
    D2.MAX-D1.SIZE_OF_COLONY YEAR_DEV,
    ID
FROM ECOLI_DATA D1
JOIN(
    SELECT
        YEAR(DIFFERENTIATION_DATE) YEAR,
        MAX(SIZE_OF_COLONY) AS MAX
    FROM ECOLI_DATA
    GROUP BY YEAR) D2
ON YEAR(D1.DIFFERENTIATION_DATE) = D2.YEAR
ORDER BY YEAR, YEAR_DEV