SELECT
    P.PRODUCT_CODE,
    P.PRICE*SUM(S.SALES_AMOUNT) SALES
FROM OFFLINE_SALE S
JOIN PRODUCT P
    ON S.PRODUCT_ID=P.PRODUCT_ID
GROUP BY S.PRODUCT_ID
ORDER BY SALES DESC, P.PRODUCT_CODE