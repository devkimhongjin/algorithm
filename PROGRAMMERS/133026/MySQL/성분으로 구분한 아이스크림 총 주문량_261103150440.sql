SELECT
    I.INGREDIENT_TYPE,
    SUM(TOTAL_ORDER) TOTAL_ORDER
FROM FIRST_HALF F
LEFT JOIN ICECREAM_INFO I
    ON F.FLAVOR=I.FLAVOR
GROUP BY I.INGREDIENT_TYPE
ORDER BY TOTAL_ORDER